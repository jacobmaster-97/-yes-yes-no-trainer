const { chromium, devices } = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { htmlPath, artifactPath, launchOptions } = require('./helpers.cjs');
const html = fs.readFileSync(htmlPath, 'utf8');

(async () => {
  const browser = await chromium.launch(launchOptions);
  try {
    const legacy = { version: 1, settings: { count: 20 }, history: [{ id: 'old-session', mode: 'standard', pitches: [{ userChoice: 'GO', correct: false }] }] };
    const context = await browser.newContext({ acceptDownloads: true });
    await context.route('http://localhost:8765/**', r => r.fulfill({ contentType: 'text/html', body: html }));
    await context.setOffline(true);
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.clock.install();
    await page.goto('http://localhost:8765/?debug=1');
    await page.evaluate(value => localStorage.setItem('yyn-trainer-v1', JSON.stringify(value)), legacy);
    await page.reload();
    assert(await page.locator('#legacySection').isVisible());
    await page.getByRole('button', { name: '開始這組訓練' }).click();
    await page.keyboard.press('Enter');
    await page.clock.runFor(3200);
    assert.equal((await snap()).session.pitches[0].selfRating, null);
    assert(await page.locator('#systemResult').isHidden());
    await page.locator('#pitchNote').fill('未自評前先記下觀察。');
    await page.reload();
    assert(await page.locator('#resumeBanner').isVisible());
    await page.locator('#resumeBtn').click();
    assert.equal((await snap()).state, 'REVIEW');
    assert.equal(await page.locator('#pitchNote').inputValue(), '未自評前先記下觀察。');
    assert(await page.locator('#systemResult').isHidden());
    await page.locator('#correctBtn').click();
    await page.locator('#editRatingBtn').click();
    assert.equal((await snap()).session.pitches[0].selfRating, null);
    assert(await page.locator('#systemResult').isHidden());
    await page.locator('#incorrectBtn').click();
    assert.equal((await snap()).session.pitches[0].selfRating, false);
    assert.equal((await snap()).session.pitches.length, 1);
    await page.keyboard.press('Enter');
    await page.clock.runFor(1300);
    await page.locator('#finishBtn').click();
    assert((await snap()).paused);
    const frozen = (await snap()).phaseMs;
    await page.clock.runFor(2000);
    assert.equal((await snap()).phaseMs, frozen);
    await page.locator('#cancelConfirm').click();
    assert.equal((await snap()).paused, false);
    await page.locator('#finishBtn').click();
    await page.locator('#acceptConfirm').click();
    assert(await page.locator('#summaryScreen').isVisible());
    assert.equal((await snap()).history[0].status, 'partial');
    assert.equal((await snap()).history[0].pitches.length, 1);
    await page.locator('#homeBtn').click();
    // A partial, unrated pitch is retained and excluded from the self-rating denominator.
    await page.getByRole('button', { name: '開始這組訓練' }).click();
    await page.keyboard.press('Enter');
    await page.clock.runFor(3200);
    await page.locator('#finishBtn').click();
    await page.locator('#acceptConfirm').click();
    assert((await page.locator('#metrics').innerText()).includes('未有樣本'));
    assert(!(await page.locator('#metrics').innerText()).includes('NaN'));
    assert.equal((await snap()).history[0].pitches[0].selfRating, null);
    await page.locator('#homeBtn').click();
    await page.locator('#clearHistory').click();
    await page.locator('#cancelConfirm').click();
    assert.equal(await page.locator('.history-row').count(), 2);
    await page.locator('#clearHistory').click();
    await page.locator('#acceptConfirm').click();
    assert.equal(await page.locator('.history-row').count(), 0);
    assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('yyn-trainer-v1'))), legacy);
    // Cross-field and impossible physical configurations fail without creating a session.
    await page.locator('#speedMin').fill('90');
    await page.getByRole('button', { name: '開始這組訓練' }).click();
    assert((await page.locator('#formError').innerText()).includes('最低球速'));
    assert(await page.locator('#homeScreen').isVisible());
    await page.locator('#speedMin').fill('40');
    await page.locator('#speedMax').fill('40');
    await page.locator('details').first().evaluate(e => e.open = true);
    await page.locator('#moundDistance').fill('24');
    await page.locator('#releaseExtension').fill('0');
    await page.getByRole('button', { name: '開始這組訓練' }).click();
    assert((await page.locator('#formError').innerText()).includes('未能形成'));
    assert(await page.locator('#homeScreen').isVisible());
    assert.deepEqual(errors, []);

    const touchContext = await browser.newContext({ ...devices['iPad (gen 7) landscape'] });
    await touchContext.route('http://localhost:8765/**', r => r.fulfill({ contentType: 'text/html', body: html }));
    await touchContext.setOffline(true);
    const tablet = await touchContext.newPage();
    tablet.on('pageerror', e => errors.push(e.message));
    await tablet.clock.install();
    await tablet.goto('http://localhost:8765/?debug=1');
    await tablet.getByRole('button', { name: '開始這組訓練' }).tap();
    await tablet.locator('#nextBtn').tap();
    await tablet.clock.runFor(1500);
    const before = await tablet.evaluate(() => { const s = YYN_DEBUG.snapshot(); return { endpoint: s.pitch.endpoint, isStrike: s.pitch.isStrike }; });
    await tablet.screenshot({ path: artifactPath('v2-ipad-flight.png'), fullPage: true });
    await tablet.setViewportSize({ width: 810, height: 1080 });
    await tablet.clock.runFor(2000);
    const after = await tablet.evaluate(() => { const s = YYN_DEBUG.snapshot(); return { endpoint: s.pitch.endpoint, isStrike: s.pitch.isStrike }; });
    assert.deepEqual(before, after);
    assert(await tablet.locator('#systemResult').isHidden());
    await tablet.locator('#incorrectBtn').tap();
    assert(await tablet.locator('#systemResult').isVisible());
    await tablet.screenshot({ path: artifactPath('v2-ipad-review.png'), fullPage: true });
    await tablet.setViewportSize({ width: 390, height: 844 });
    assert(await tablet.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await tablet.screenshot({ path: artifactPath('v2-mobile.png'), fullPage: true });

    const deniedContext = await browser.newContext();
    await deniedContext.route('http://localhost:8765/**', r => r.fulfill({ contentType: 'text/html', body: html }));
    const denied = await deniedContext.newPage();
    await denied.addInitScript(() => Object.defineProperty(window, 'localStorage', { get() { throw new Error('storage denied'); } }));
    await denied.clock.install();
    await denied.goto('http://localhost:8765/?debug=1');
    assert(await denied.locator('#storageWarning').isVisible());
    await denied.getByRole('button', { name: '開始這組訓練' }).click();
    await denied.keyboard.press('Enter');
    await denied.clock.runFor(3200);
    await denied.locator('#correctBtn').click();
    assert.equal((await denied.evaluate(() => YYN_DEBUG.snapshot())).session.pitches[0].selfRating, true);
    assert.deepEqual(errors, []);
    console.log('PASS: saved pending drafts and resume; rating edits; partial records; zero denominators; confirmation pause/cancel; legacy preservation; invalid settings; iPad touch and rotation; phone layout; denied storage fallback');
    async function snap() { return page.evaluate(() => YYN_DEBUG.snapshot()); }
  } finally {
    await browser.close();
  }
})().catch(e => { console.error(e); process.exit(1); });
