const { chromium } = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { htmlPath, artifactPath, launchOptions } = require('./helpers.cjs');

(async () => {
  const browser = await chromium.launch(launchOptions);
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, acceptDownloads: true });
    const page = await context.newPage();
    const errors = [], requests = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('request', r => requests.push(r.url()));
    await context.route('http://localhost:8765/**', r => r.fulfill({ contentType: 'text/html', body: fs.readFileSync(htmlPath, 'utf8') }));
    await context.setOffline(true);
    await page.clock.install();
    await page.goto('http://localhost:8765/?debug=1');
    assert.equal(await page.locator('#speedMin').inputValue(), '50');
    assert.equal(await page.locator('#speedMax').inputValue(), '80');
    await page.screenshot({ path: artifactPath('v2-home.png'), fullPage: true });
    await page.getByRole('button', { name: '開始這組訓練' }).click();
    const first = await snap();
    assert.equal(first.session.version, 2);
    assert.equal(first.session.settings.count, 20);
    await page.keyboard.press('1');
    assert.equal((await snap()).session.pitches.length, 0);
    await page.keyboard.press('Enter');
    await page.clock.runFor(1200);
    assert.equal((await snap()).state, 'BALL_IN_FLIGHT');
    await page.keyboard.press('p');
    const paused = await snap();
    await page.clock.runFor(3000);
    assert.equal((await snap()).phaseMs, paused.phaseMs);
    await page.keyboard.press('1');
    assert.equal((await snap()).session.pitches.length, 0);
    await page.keyboard.press('p');
    await page.clock.runFor(3000);
    let s = await snap();
    assert.equal(s.state, 'REVIEW');
    assert.equal(s.session.pitches.length, 1);
    assert.equal(s.session.pitches[0].selfRating, null);
    assert.equal(typeof s.session.pitches[0].isStrike, 'boolean');
    assert(await page.locator('#systemResult').isHidden());
    assert(await page.locator('#nextBtn').isDisabled());
    await page.clock.runFor(30000);
    assert.equal((await snap()).session.pitches[0].selfRating, null);
    await page.locator('#userAction').selectOption('GO');
    await page.locator('#pitchNote').fill('=SUM(1,2) <img src=x>');
    await page.keyboard.press('Tab');
    await page.locator('#correctBtn').click();
    for (let n = 0; n < 6; n++) await page.keyboard.press(n % 2 ? '1' : '2');
    assert.equal((await snap()).session.pitches.length, 1);
    assert.equal((await snap()).session.pitches[0].selfRating, true);
    assert(await page.locator('#systemResult').isVisible());
    await page.screenshot({ path: artifactPath('v2-self-review.png'), fullPage: true });
    await page.locator('#replayBtn').click();
    await page.clock.runFor(3200);
    s = await snap();
    assert.equal(s.session.pitches.length, 1);
    assert.equal(s.session.pitches[0].selfRating, true);
    for (let i = 1; i < 20; i++) {
      await page.keyboard.press('Enter');
      await page.clock.runFor(3200);
      s = await snap();
      assert.equal(s.state, 'REVIEW');
      assert.equal(s.session.pitches.length, i + 1);
      assert(await page.locator('#systemResult').isHidden());
      await page.keyboard.press(i % 2 ? '2' : '1');
      assert.equal((await snap()).session.pitches[i].selfRating, i % 2 === 0);
    }
    s = await snap();
    assert.equal(s.history.length, 1);
    assert.equal(s.draft, null);
    assert.equal(s.session.status, 'completed');
    assert.equal(s.session.pitches.filter(r => r.selfRating).length, 10);
    assert.equal(s.session.pitches.filter(r => r.isStrike).length, 12);
    assert(s.session.pitches.some(r => !r.isStrike && r.selfRating === true));
    assert(s.session.pitches.every(r => !('samples' in r) && !('reactionMs' in r)));
    await page.locator('#editRatingBtn').click();
    assert.equal((await snap()).history.length, 0);
    assert.equal((await snap()).session.pitches.at(-1).selfRating, null);
    await page.locator('#incorrectBtn').click();
    assert.equal((await snap()).history.length, 1);
    assert.equal((await snap()).draft, null);
    await page.keyboard.press('Enter');
    assert(await page.locator('#summaryScreen').isVisible());
    assert(!(await page.locator('#metrics').innerText()).includes('NaN'));
    await page.locator('#sessionNote').fill('觀察出手位置，下一組保持準備。');
    const jsonEvent = page.waitForEvent('download');
    await page.locator('#exportJSON').click();
    await (await jsonEvent).saveAs(artifactPath('v2-export.json'));
    const exported = JSON.parse(fs.readFileSync(artifactPath('v2-export.json'), 'utf8'));
    assert.equal(exported.pitches.length, 20);
    assert.equal(exported.pitches[0].selfRating, true);
    assert.equal(exported.note, '觀察出手位置，下一組保持準備。');
    const csvEvent = page.waitForEvent('download');
    await page.locator('#exportCSV').click();
    await (await csvEvent).saveAs(artifactPath('v2-export.csv'));
    const csv = fs.readFileSync(artifactPath('v2-export.csv'), 'utf8');
    assert.equal(csv.split('\r\n').length, 21);
    assert(csv.includes('selfRating') && csv.includes('isStrike'));
    assert(csv.includes("'=SUM(1,2)"));
    await page.screenshot({ path: artifactPath('v2-summary.png'), fullPage: true });
    await page.reload();
    assert.equal(await page.locator('.history-row').count(), 1);
    await page.locator('.history-row button').click();
    assert.equal(await page.locator('#sessionNote').inputValue(), exported.note);
    await page.locator('#retryBtn').click();
    const repeated = await snap();
    assert.deepEqual(repeated.pitch.endpoint, first.pitch.endpoint);
    assert.equal(repeated.pitch.pitchDurationMs, first.pitch.pitchDurationMs);
    await page.goto('http://localhost:8765/');
    assert.equal(await page.evaluate(() => typeof window.YYN_DEBUG), 'undefined');
    assert.deepEqual(errors, []);
    assert(requests.every(url => url.startsWith('http://localhost:8765/')));
    console.log('PASS: complete 20-pitch personal log; rating locked until arrival; independent classification; no timeout scoring; pause/replay; notes; JSON/CSV; persisted history; offline; debug defaults off');
    async function snap() { return page.evaluate(() => YYN_DEBUG.snapshot()); }
  } finally {
    await browser.close();
  }
})().catch(e => { console.error(e); process.exit(1); });
